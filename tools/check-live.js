'use strict';

/* Is the live site actually serving what this build produced?
 *
 * The gap this closes: the daily publishing job adds articles to the repo, the
 * repo gets pushed, and nothing else happens. Locally `node tools/build.js`
 * writes 35 URLs; the live site can still be serving 31 of them from a deploy
 * made days earlier. Nothing in the build can see that, because the build only
 * knows about dist/ — so the question "did my new article go live?" had no
 * honest answer short of opening the site and counting.
 *
 * The check is the one that cannot be faked: the sitemap the live server
 * returns is generated by the same build as the pages it is serving, so a URL
 * missing from it is a page that genuinely is not online.
 *
 * Run:  node tools/check-live.js
 * Exit: 0 everything is live, 1 something is missing, 2 the check could not run
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const { site } = require(path.join(ROOT, 'src', 'config.js'));

const LIVE_SITEMAP = site.domain.replace(/\/$/, '') + '/sitemap.xml';
const LOCAL_SITEMAP = path.join(ROOT, 'dist', 'sitemap.xml');

function locs(xml) {
  return [...xml.matchAll(/<loc>\s*([^<]+?)\s*<\/loc>/g)].map((m) => m[1]);
}

function main() {
  if (!fs.existsSync(LOCAL_SITEMAP)) {
    console.error('no dist/sitemap.xml — run `node tools/build.js` first');
    process.exit(2);
  }

  const local = new Set(locs(fs.readFileSync(LOCAL_SITEMAP, 'utf8')));

  fetch(LIVE_SITEMAP, { redirect: 'follow' })
    .then((r) => {
      if (!r.ok) {
        console.error(`live sitemap returned HTTP ${r.status} — ${LIVE_SITEMAP}`);
        process.exit(2);
      }
      return r.text();
    })
    .then((xml) => {
      const live = new Set(locs(xml));

      const missing = [...local].filter((u) => !live.has(u)).sort();
      const extra = [...live].filter((u) => !local.has(u)).sort();

      console.log(`live  ${live.size} URLs   local ${local.size} URLs`);
      console.log('');

      if (missing.length) {
        console.log(`not live yet (${missing.length}):`);
        for (const u of missing) console.log('    ' + u.replace(site.domain, ''));
      } else {
        console.log('every URL in this build is live.');
      }

      if (extra.length) {
        console.log('');
        console.log(`live but not in this build (${extra.length}):`);
        for (const u of extra) console.log('    ' + u.replace(site.domain, ''));
      }

      console.log('');
      if (missing.length) {
        console.log(
          'These pages exist in dist/ and are not being served. The build is\n' +
          'not what publishes them — run the deploy:\n\n' +
          '    node tools/build.js && npx wrangler deploy'
        );
        process.exit(1);
      }
      process.exit(0);
    })
    .catch((e) => {
      console.error(`could not reach the live sitemap (${e.message})`);
      process.exit(2);
    });
}

main();
